// Turns paintings from the dashboard's own collection (public/art, lib/art.json) into TV-ready
// wallpapers: 1920x1080 cover crop with the readability scrim baked in, saved as JPEG in
// src/img/wallpapers/, plus the catalog src/js/wallpapers.js. The scrim is part of the image so
// the TV never composites a gradient over a painting at runtime (see the header of style.css).
//
//   node launcher/scripts/paintings.mjs
//
// Needs Google Chrome (headless, for the render) and macOS `sips` (JPEG + thumbnails).
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, mkdirSync, rmSync, statSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const launcher = resolve(here, '..');
const repo = resolve(launcher, '..');
const outDir = join(launcher, 'src/img/wallpapers');
const art = JSON.parse(readFileSync(join(repo, 'lib/art.json'), 'utf8'));

// Landscapes that survive a 16:9 crop. `position` is the CSS background-position of the crop.
const PICKS = [
    { slug: 'hokusai-the-great-wave-off-kanagawa', position: 'center 55%' },
    { slug: 'monet-stacks-of-wheat' },
    { slug: 'sisley-the-loire', position: 'center 40%' },
    { slug: 'seurat-a-sunday-on-la-grande-jatte-1884' },
    { slug: 'homer-the-herring-net' },
    { slug: 'monet-the-beach-at-sainte-adresse' },
    { slug: 'caillebotte-paris-street-rainy-day', position: 'center 45%' },
    { slug: 'sisley-watering-place-at-marly' },
    { slug: 'hiroshige-evening-snow-at-kanbara', position: 'center 40%' },
    { slug: 'homer-breaking-storm-coast-of-maine' },
    { slug: 'monet-arrival-of-the-normandy-train-gare-saint-lazare' },
    { slug: 'sargent-olive-trees-corfu' }
];

// Darker behind the clock (top left) and under the two rows of tiles (bottom half).
const SCRIM = [
    'radial-gradient(1300px 680px at 0% 0%, rgba(10,12,10,0.84), rgba(10,12,10,0.4) 45%, rgba(10,12,10,0) 80%)',
    'linear-gradient(to bottom, rgba(10,12,10,0) 0%, rgba(10,12,10,0.06) 30%, rgba(10,12,10,0.58) 47%, rgba(10,12,10,0.84) 66%, rgba(10,12,10,0.92) 100%)'
].join(',');

const thumbDir = join(outDir, 'thumbs');
rmSync(outDir, { recursive: true, force: true });
mkdirSync(thumbDir, { recursive: true });
const tmp = mkdtempSync(join(tmpdir(), 'paintings-'));

const catalog = [];
for (const pick of PICKS) {
    const work = art.find((w) => w.slug === pick.slug);
    if (!work) throw new Error('Not in lib/art.json: ' + pick.slug);
    const html = join(tmp, pick.slug + '.html');
    const png = join(tmp, pick.slug + '.png');
    const src = 'file://' + join(repo, 'public', work.image).split('/').map(encodeURIComponent).join('/');
    writeFileSync(html, `<!DOCTYPE html><body style="margin:0;width:1920px;height:1080px;background:${SCRIM},` +
        `url('${src}') ${pick.position || 'center'} / cover no-repeat #111613"></body>`);
    execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--hide-scrollbars', '--window-size=1920,1080',
        '--allow-file-access-from-files', '--virtual-time-budget=5000', `--user-data-dir=${join(tmp, 'profile')}`,
        `--screenshot=${png}`, 'file://' + html], { stdio: 'ignore' });
    const out = join(outDir, pick.slug + '.jpg');
    execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '70', png, '--out', out], { stdio: 'ignore' });
    execFileSync('sips', ['-Z', '320', '-s', 'formatOptions', '78', out, '--out', join(thumbDir, pick.slug + '.jpg')], { stdio: 'ignore' });
    catalog.push({
        key: pick.slug,
        title: work.title,
        file: 'img/wallpapers/' + pick.slug + '.jpg',
        thumb: 'img/wallpapers/thumbs/' + pick.slug + '.jpg',
        credit: work.artist + ', ' + work.date,
        artist: work.artist,
        date: work.date,
        detail: work.medium + ' · ' + work.collection
    });
    console.log(`${pick.slug}.jpg  ${(statSync(out).size / 1024).toFixed(0)} KB`);
}
rmSync(tmp, { recursive: true, force: true });

writeFileSync(join(launcher, 'src/js/wallpapers.js'),
    '/* Generated by scripts/paintings.mjs from lib/art.json. Public-domain paintings. */\n' +
    'window.WALLPAPERS = ' + JSON.stringify(catalog, null, 4) + ';\n');
console.log(`Wrote ${catalog.length} entries to launcher/src/js/wallpapers.js`);
